def read(path):
    return json.loads(Path(path).read_text(encoding="utf-8-sig"))


def sha(path):
    with Path(path).open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def write_new(path, value):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists(): raise FileExistsError(path)
    temporary = path.with_name("." + path.name + ".pending")
    with temporary.open("w", encoding="utf-8") as stream:
        json.dump(value, stream, ensure_ascii=False, indent=2, allow_nan=False)
    temporary.rename(path)


def save_frame(path, frame):
    """Resume an unsealed fold only when regenerated bytes match its evidence."""
    path = Path(path)
    temporary = path.with_name("." + path.name + ".pending")
    if path.suffix == ".parquet":
        frame.write_parquet(temporary, compression="zstd")
    else:
        frame.write_csv(temporary, float_precision=17)
    if path.exists():
        assert sha(path) == sha(temporary), f"Regenerated artifact differs; both preserved: {path}"
        temporary.unlink()
    else:
        temporary.rename(path)


def log(value):
    print(f"[{datetime.now():%H:%M:%S}] {value}", flush=True)


def source_map():
    return {f"experiments/{name}.py": sha(ROOT / f"experiments/{name}.py") for name in
            ("r7_complement", "r7_complement_signal", "r7_complement_diagnostics", "r7_complement_audit")}


def tests():
    from experiments import r7_complement_signal as signal, r7_complement_diagnostics as diagnostic, r7_complement_audit as audit
    results = {"signal": signal.tests(), "diagnostic": diagnostic.synthetic_tests(),
               "audit": audit.synthetic_tests(), "runner": runner_tests()}
    assert all(value["status"] == "passed" for value in results.values())
    record = {"status": "passed", "source_sha256": source_map(), "results": results,
              "historical_candidate_scores_computed": False}
    write_new(OUT / "tests.json", record)
    log(json.dumps(record, ensure_ascii=False))


def runner_tests():
    """Exercise actual interrupted-write recovery and confirmation read ordering."""
    global OUT, load_year
    original_out, original_loader = OUT, load_year
    try:
        with tempfile.TemporaryDirectory(prefix="r7-control-tests-") as temporary:
            OUT = Path(temporary)
            loaded = []
            def forbidden_loader(year):
                loaded.append(year)
                raise AssertionError("Confirmation labels read before gate")
            load_year = forbidden_loader
            write_new(OUT / "fold_2023.json", {"not_a_valid_fold": True})
            try:
                score_fold(2023)
            except FileNotFoundError:
                pass
            else:
                raise AssertionError("Missing development gate accepted")
            assert not loaded
            fixture = pl.DataFrame({"a": [1., .25], "b": [None, 2.]})
            for extension in ("csv", "parquet"):
                path = OUT / ("resume." + extension)
                save_frame(path, fixture)
                before = (sha(path), path.stat().st_mtime_ns)
                save_frame(path, fixture)
                assert (sha(path), path.stat().st_mtime_ns) == before
                try:
                    save_frame(path, fixture.with_columns(pl.lit(99.).alias("a")))
                except AssertionError:
                    assert (sha(path), path.stat().st_mtime_ns) == before
                    assert path.with_name("." + path.name + ".pending").is_file()
                else:
                    raise AssertionError("Differing resume overwrote prior artifact")
            (OUT / ".atomic.json.pending").write_text("interrupted", encoding="utf-8")
            write_new(OUT / "atomic.json", {"done": True})
            assert read(OUT / "atomic.json") == {"done": True}
            try:
                write_new(OUT / "atomic.json", {"done": False})
            except FileExistsError:
                assert read(OUT / "atomic.json") == {"done": True}
            else:
                raise AssertionError("Completed JSON overwritten")
            write_new(OUT / "protocol.json", {"synthetic": True})
            for filename in required_artifacts(2020):
                (OUT / filename).write_text("synthetic evidence", encoding="utf-8")
            pending_fold = OUT / ".fold_2020.json.pending"
            pending_fold.write_text("interrupted fold commit", encoding="utf-8")
            recovered = {"year": 2020, "candidate_key": PRIMARY,
                "protocol_sha256": sha(OUT / "protocol.json"), "input_sha256": {},
                "artifact_sha256": {name: sha(OUT / name) for name in sorted(required_artifacts(2020))}}
            write_new(OUT / "fold_2020.json", recovered)
            check_fold(read(OUT / "fold_2020.json"), 2020)
            assert not pending_fold.exists()
    finally:
        OUT, load_year = original_out, original_loader
    return {"status": "passed", "confirmation_guard_precedes_any_cache_or_label_read": True,
            "equal_resume_preserves_original_bytes_and_mtime": True,
            "changed_resume_preserves_both_artifacts_and_fails": True,
            "pending_json_recoverable_and_completed_json_immutable": True,
            "interrupted_fold_commit_does_not_hash_its_pending_file": True}


