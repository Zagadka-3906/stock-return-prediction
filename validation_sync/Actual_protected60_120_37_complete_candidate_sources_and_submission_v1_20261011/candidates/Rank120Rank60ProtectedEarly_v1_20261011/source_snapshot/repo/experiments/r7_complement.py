def verify_protocol():
    p = read(OUT / "protocol.json")
    assert p["config"] == CONFIG and p["gates"] == GATES and p["candidate_count"] == 1
    for relative, digest in p["input_sha256"].items():
        assert sha(ROOT / relative) == digest, relative
    return p


def _stage_guard():
    d = read(OUT / "development.json")
    assert d["protocol_sha256"] == sha(OUT / "protocol.json") and d["development_gate_passed"] is True
    assert d["completed_years"] == list(DEVELOPMENT)
    folds = checked_folds(d)
    assert gate(folds, "development") == d["gate"]
    assert d["point_gate_passed"] == d["gate"]["passed"] is True
    assert set(d["bootstrap"]) == {"baseline", "ensemble4"}
    for result in d["bootstrap"].values():
        assert result["block_days"] == 20 and result["draws"] == 20000 and result["seed"] == 2026
        assert result["bootstrap_share_positive"] >= .8
    audit = read(OUT / "independent_audit/development/score_audit.json")
    assert audit["status"] == "passed" and audit["stage_gate_passed"] is True
    assert audit["stage_record_sha256"] == sha(OUT / "development.json")
    assert audit["protocol_sha256"] == sha(OUT / "protocol.json")
    assert audit["source_sha256"] == sha(ROOT / "experiments/r7_complement_audit.py")
    for relative, digest in audit["artifacts_sha256"].items():
        assert sha(ROOT / relative) == digest


def neural_path(year):
    if year in DEVELOPMENT:
        return R6 / f"raw_feature_identity_{year}.parquet"
    assert year in CONFIRMATION
    _stage_guard()
    return OUT / "neural_training" / f"raw_feature_identity_{year}.parquet"


def train_confirmation(year):
    _stage_guard()
    from experiments import r6_transformer as trainer
    protocol = verify_protocol()
    assert dict(trainer.CONFIG) == protocol["confirmation_training"]
    target = OUT / "neural_training"
    target.mkdir(parents=True, exist_ok=True)
    training_protocol = {"parent_protocol_sha256": sha(OUT / "protocol.json"),
                         "training_source_sha256": sha(Path(trainer.__file__)),
                         "config": dict(trainer.CONFIG), "years": list(CONFIRMATION),
                         "no_r6_outputs_modified": True}
    if (target / "protocol.json").exists():
        assert read(target / "protocol.json") == training_protocol
    else:
        write_new(target / "protocol.json", training_protocol)
    old = trainer.OUT
    try:
        trainer.OUT = target
        trainer.train_fold(year, ["feature_identity"])
    finally:
        trainer.OUT = old


def score_fold(year):
    assert year in DEVELOPMENT + CONFIRMATION
    if year in CONFIRMATION: _stage_guard()
    destination = OUT / f"fold_{year}.json"
    if destination.exists():
        result = read(destination)
        check_fold(result, year)
        return result
    frame, _, provenance = load_year(year)
    raw_path = neural_path(year)
    nn = pl.read_parquet(raw_path).with_columns(pl.col("trade_date").cast(frame.schema["trade_date"]))
    neural = align_raw(frame, nn)
    zero = prediction(frame, neural, 0.)
    assert np.array_equal(zero, frame["pred"].to_numpy()), "Zero-weight control changed r4"
    raw = blend_raw(frame, neural, CONFIG["neural_weight"])
    pred = prediction(frame, neural, CONFIG["neural_weight"])
    corrupted = frame.with_columns(pl.lit(123456.).alias("y_ret_1d"), pl.lit(False).alias("future_available"))
    assert np.array_equal(raw, blend_raw(corrupted, neural))
    assert np.array_equal(pred, prediction(corrupted, neural))
    count = frame["ts_code"].n_unique() * 50
    assert np.array_equal(pred[:count], prediction(frame.head(count), neural[:count]))
    assert np.isfinite(pred).all() and (pred[~frame["price_valid"].to_numpy()] < -1).all()
    result = {"year": year, "candidate_key": PRIMARY, "protocol_sha256": sha(OUT / "protocol.json"),
              "references": {}, "provenance": provenance,
              "input_sha256": dict(provenance["verified_input_sha256"])}
    result["input_sha256"][raw_path.relative_to(ROOT).as_posix()] = sha(raw_path)
    if year in CONFIRMATION:
        metadata = read(OUT / "neural_training" / f"training_feature_identity_{year}.json")
        for name in metadata["artifact_sha256"]:
            path = OUT / "neural_training" / name
            result["input_sha256"][path.relative_to(ROOT).as_posix()] = sha(path)
        for path in (OUT / "neural_training/protocol.json", OUT / "neural_training" / f"training_feature_identity_{year}.json"):
            result["input_sha256"][path.relative_to(ROOT).as_posix()] = sha(path)
    expected = read(R4 / "summary.json")["metrics"][str(year)]
    for name in ("baseline", "ensemble4"):
        reference = pl.read_parquet(R4 / f"predictions_{name}_{year}.parquet").sort("trade_date", "ts_code")
        assert reference.select(KEYS).equals(frame.select(KEYS))
        metrics, daily = score_official(frame, reference["pred"].to_numpy())
        assert all(abs(metrics[k]-v) <= 1e-12 for k, v in expected[name].items())
        result["references"][name] = metrics
        save_frame(OUT / f"daily_{name}_{year}.csv", daily)
    metrics, daily = score_official(frame, pred)
    raw_metrics, raw_daily = score_official(frame, raw)
    result.update({"metrics": metrics, "raw_metrics": raw_metrics,
        "tests": {"zero_weight_exact_r4": True, "labels_and_future_available_ignored": True,
                  "prefix_50days_exact": True, "finite_predictions": True, "invalid_price_low": True}})
    save_frame(OUT / f"daily_{PRIMARY}_{year}.csv", daily)
    save_frame(OUT / f"daily_raw_{PRIMARY}_{year}.csv", raw_daily)
    save_frame(OUT / f"predictions_{PRIMARY}_{year}.parquet",
               frame.with_columns(pl.Series("pred_raw", raw), pl.Series("pred", pred)))
    if year in DEVELOPMENT:
        diagnostic_daily, diagnostic_summary = diagnose(frame, neural)
        save_frame(OUT / f"diagnostic_daily_{year}.csv", diagnostic_daily)
        diagnostic_path = OUT / f"diagnostic_{year}.json"
        if diagnostic_path.exists():
            assert read(diagnostic_path) == diagnostic_summary, "Unsealed diagnostic changed on resume"
        else:
            write_new(diagnostic_path, diagnostic_summary)
    result["artifact_sha256"] = {name: sha(OUT / name) for name in sorted(required_artifacts(year))}
    write_new(destination, result)
    log(f"{year} neural10 score={metrics['final_score']:.9f}, delta_r4={metrics['final_score']-result['references']['ensemble4']['final_score']:+.9f}")
    return result


def gate(folds, stage):
    thresholds = GATES[stage]
    comparisons = {}
    for name in ("baseline", "ensemble4"):
        delta = [f["metrics"]["final_score"]-f["references"][name]["final_score"] for f in folds]
        ic = [f["metrics"]["ic_mean"]-f["references"][name]["ic_mean"] for f in folds]
        comparisons[name] = {"score_deltas": {str(f["year"]): x for f, x in zip(folds, delta)},
            "mean_score_delta": float(np.mean(delta)), "worst_year_score_delta": float(min(delta)),
            "mean_ic_delta": float(np.mean(ic)), "passed": bool(np.mean(delta) >= thresholds["mean_score_delta_min"]
                and min(delta) >= thresholds["worst_year_score_delta_min"] and np.mean(ic) >= thresholds["mean_ic_delta_min"])}
    return {"comparisons": comparisons, "passed": all(v["passed"] for v in comparisons.values())}


def checked_folds(record):
    folds = []
    for year in record["completed_years"]:
        name = f"fold_{year}.json"
        assert sha(OUT / name) == record["fold_sha256"][name]
        fold = read(OUT / name)
        check_fold(fold, year)
        folds.append(fold)
    return folds


def required_artifacts(year):
    required = {f"predictions_{PRIMARY}_{year}.parquet", f"daily_{PRIMARY}_{year}.csv",
                f"daily_raw_{PRIMARY}_{year}.csv", f"daily_baseline_{year}.csv", f"daily_ensemble4_{year}.csv"}
    if year in DEVELOPMENT: required |= {f"diagnostic_daily_{year}.csv", f"diagnostic_{year}.json"}
    return required


def check_fold(fold, year):
    assert fold["year"] == year and fold["candidate_key"] == PRIMARY
    assert fold["protocol_sha256"] == sha(OUT / "protocol.json")
    assert set(fold["artifact_sha256"]) == required_artifacts(year)
    for relative, digest in fold["artifact_sha256"].items(): assert sha(OUT / relative) == digest
    for relative, digest in fold["input_sha256"].items(): assert sha(ROOT / relative) == digest


def stage(name):
    assert name in ("development", "confirmation")
    verify_protocol()
    if (OUT / f"{name}.json").exists(): raise FileExistsError("Preserve completed stage")
    years = DEVELOPMENT if name == "development" else CONFIRMATION
    if name == "confirmation": _stage_guard()
    folds = []
    for year in years:
        if name == "confirmation": train_confirmation(year)
        folds.append(score_fold(year))
    point = gate(folds, name)
    bootstrap = None
    if point["passed"]:
        candidate = {year: pl.read_csv(OUT / f"daily_{PRIMARY}_{year}.csv") for year in years}
        bootstrap = {key: paired_block_bootstrap(candidate,
            {year: pl.read_csv(OUT / f"daily_{key}_{year}.csv") for year in years}, block_days=20, draws=20000, seed=2026)
            for key in ("baseline", "ensemble4")}
    passed = point["passed"] and all(v["bootstrap_share_positive"] >= .8 for v in bootstrap.values())
    record = {"protocol_sha256": sha(OUT / "protocol.json"), "primary_candidate": PRIMARY,
              "completed_years": list(years), "gate": point, "point_gate_passed": point["passed"],
              f"{name}_gate_passed": passed, "bootstrap": bootstrap,
              "fold_sha256": {f"fold_{year}.json": sha(OUT / f"fold_{year}.json") for year in years},
              "no_publication": True, "no_weight_or_candidate_selection": True}
    if name == "confirmation":
        record["development_sha256"] = sha(OUT / "development.json")
        record["development_audit_sha256"] = sha(OUT / "independent_audit/development/score_audit.json")
    verify_protocol()
    write_new(OUT / f"{name}.json", record)
    log(json.dumps({"stage": name, "passed": passed, "gate": point}, ensure_ascii=False))


